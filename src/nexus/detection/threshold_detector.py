"""Threshold-based anomaly detector implementation."""

from typing import Any, Mapping, Optional, Sequence

from nexus.detection.exceptions import InvalidRuleError
from nexus.detection.models import AnomalyEvent, DetectionSource
from nexus.detection.rules import ThresholdRule, get_default_rules
from nexus.telemetry.models import KPISnapshot
from nexus.topology.enums import NodeType


def extract_snapshot_metrics(snapshot: KPISnapshot) -> dict[str, float]:
    """Extract present numeric KPI metrics from a snapshot without fabricating missing values.

    Returns a dict mapping metric_name to float value.
    """
    metrics: dict[str, float] = {
        "throughput_mbps": snapshot.performance.throughput_mbps,
        "latency_ms": snapshot.performance.latency_ms,
        "connection_drop_rate_pct": snapshot.reliability.connection_drop_rate_pct,
        "availability_pct": snapshot.reliability.availability_pct,
    }
    if snapshot.reliability.handover_success_rate_pct is not None:
        metrics["handover_success_rate_pct"] = snapshot.reliability.handover_success_rate_pct

    if snapshot.radio is not None:
        metrics["rsrp_dbm"] = snapshot.radio.rsrp_dbm
        metrics["sinr_db"] = snapshot.radio.sinr_db
        metrics["prb_utilization_pct"] = snapshot.radio.prb_utilization_pct

    return metrics


class ThresholdDetector:
    """Evaluates telemetry snapshots against configurable threshold detection rules."""

    def __init__(self, rules: Optional[Sequence[ThresholdRule]] = None) -> None:
        rule_list = list(get_default_rules() if rules is None else rules)

        seen_ids: set[str] = set()
        for r in rule_list:
            if not isinstance(r, ThresholdRule):
                raise InvalidRuleError(f"Expected ThresholdRule instance, got {type(r).__name__}")
            if r.rule_id in seen_ids:
                raise InvalidRuleError(f"Duplicate rule_id '{r.rule_id}' in detector configuration")
            seen_ids.add(r.rule_id)

        self._rules: tuple[ThresholdRule, ...] = tuple(rule_list)
        self._rules_by_id: dict[str, ThresholdRule] = {r.rule_id: r for r in self._rules}

    @property
    def rules(self) -> tuple[ThresholdRule, ...]:
        """Return the immutable tuple of configured rules."""
        return self._rules

    def get_rule(self, rule_id: str) -> Optional[ThresholdRule]:
        """Look up a rule by ID."""
        return self._rules_by_id.get(rule_id)

    def evaluate_snapshot(
        self,
        snapshot: KPISnapshot,
        node_type: Optional[NodeType] = None,
    ) -> list[AnomalyEvent]:
        """Evaluate a single telemetry snapshot against all applicable threshold rules.

        Args:
            snapshot: KPISnapshot instance to evaluate.
            node_type: Optional NodeType of the target node to enforce node-type filtering.

        Returns:
            List of AnomalyEvent instances generated by rule violations.
        """
        metrics = extract_snapshot_metrics(snapshot)
        anomalies: list[AnomalyEvent] = []

        for rule in self._rules:
            if not rule.enabled:
                continue
            if not rule.applies_to_node_type(node_type):
                continue
            if rule.metric_name not in metrics:
                continue

            val = metrics[rule.metric_name]
            if rule.evaluate(val):
                desc = rule.description or (
                    f"Threshold breached: {rule.metric_name} ({val}) {rule.operator.value} {rule.threshold}"
                )
                anomalies.append(
                    AnomalyEvent(
                        node_id=snapshot.node_id,
                        metric_name=rule.metric_name,
                        timestamp=snapshot.timestamp,
                        source=DetectionSource.THRESHOLD,
                        rule_id=rule.rule_id,
                        severity=rule.severity,
                        current_value=val,
                        threshold=rule.threshold,
                        description=desc,
                        evidence={
                            "rule_id": rule.rule_id,
                            "metric": rule.metric_name,
                            "operator": rule.operator.value,
                            "threshold": rule.threshold,
                            "observed_value": val,
                            "clear_threshold": rule.clear_threshold,
                        },
                    )
                )

        return anomalies

    def check_recovery(self, snapshot: KPISnapshot, rule_id: str) -> Optional[bool]:
        """Check whether the metric in snapshot satisfies the rule's recovery condition.

        Args:
            snapshot: Latest KPISnapshot for the monitored node.
            rule_id: The rule to check recovery for.

        Returns:
            True if the metric is present and meets the recovery condition.
            False if the metric is present but does not meet the recovery condition (still in violation or hysteresis band).
            None if the rule does not exist or the metric is absent in the snapshot.
        """
        rule = self._rules_by_id.get(rule_id)
        if rule is None:
            return None

        metrics = extract_snapshot_metrics(snapshot)
        if rule.metric_name not in metrics:
            return None

        val = metrics[rule.metric_name]
        return rule.is_cleared(val)
