"""Alarm lifecycle management, deduplication, and state tracking."""

from dataclasses import replace
from datetime import datetime
from typing import Mapping, Optional, Sequence

from nexus.detection.models import (
    Alarm,
    AlarmStatus,
    AnomalyEvent,
    DetectionSource,
    _normalize_utc_timestamp,
)

AlarmKey = tuple[str, str, str, DetectionSource]


class AlarmManager:
    """Manages active alarm deduplication, updates, clearing, and historical audit trail."""

    def __init__(self) -> None:
        # Key: (node_id, metric_name, rule_id, source) -> active Alarm instance
        self._active_alarms: dict[AlarmKey, Alarm] = {}
        # Chronological audit log of cleared alarms
        self._cleared_history: list[Alarm] = []
        self._alarm_counter: int = 0

    @property
    def active_alarms_count(self) -> int:
        return len(self._active_alarms)

    @property
    def cleared_alarms_count(self) -> int:
        return len(self._cleared_history)

    def _next_alarm_id(self, node_id: str, rule_id: str) -> str:
        self._alarm_counter += 1
        return f"ALARM-{node_id}-{rule_id}-{self._alarm_counter:05d}"

    def process_anomaly(self, event: AnomalyEvent) -> tuple[Alarm, bool]:
        """Ingest an anomaly event, creating a new alarm or updating an active one.

        Args:
            event: AnomalyEvent generated by a detector.

        Returns:
            Tuple of (Alarm, is_new: bool).
        """
        key: AlarmKey = (event.node_id, event.metric_name, event.rule_id, event.source)

        if key in self._active_alarms:
            # Update existing active alarm
            existing = self._active_alarms[key]
            updated = replace(
                existing,
                current_value=event.current_value,
                last_seen=event.timestamp,
                observation_count=existing.observation_count + 1,
                severity=event.severity,
                threshold=event.threshold,
                description=event.description,
                evidence=event.evidence,
            )
            self._active_alarms[key] = updated
            return updated, False
        else:
            # Create new active alarm
            alarm_id = self._next_alarm_id(event.node_id, event.rule_id)
            new_alarm = Alarm(
                alarm_id=alarm_id,
                node_id=event.node_id,
                rule_id=event.rule_id,
                metric_name=event.metric_name,
                source=event.source,
                severity=event.severity,
                current_value=event.current_value,
                threshold=event.threshold,
                first_seen=event.timestamp,
                last_seen=event.timestamp,
                observation_count=1,
                status=AlarmStatus.ACTIVE,
                cleared_at=None,
                description=event.description,
                evidence=event.evidence,
            )
            self._active_alarms[key] = new_alarm
            return new_alarm, True

    def clear_alarm(self, key: AlarmKey, cleared_at: datetime) -> Optional[Alarm]:
        """Clear an active alarm and archive it into cleared history.

        Validates timestamp and constructs cleared alarm transactionally before mutating state.

        Args:
            key: Deduplication key (node_id, metric_name, rule_id, source).
            cleared_at: Timestamp when recovery was confirmed.

        Returns:
            The cleared Alarm instance, or None if no active alarm matched the key.
        """
        if key not in self._active_alarms:
            return None

        active = self._active_alarms[key]
        norm_cleared_at = _normalize_utc_timestamp("cleared_at", cleared_at)
        cleared = replace(
            active,
            status=AlarmStatus.CLEARED,
            cleared_at=norm_cleared_at,
        )
        # Mutate internal state only after successful validation and construction
        del self._active_alarms[key]
        self._cleared_history.append(cleared)
        return cleared

    def snapshot_state(self) -> tuple[dict[AlarmKey, Alarm], list[Alarm], int]:
        """Snapshot internal state for transactional rollback."""
        return (dict(self._active_alarms), list(self._cleared_history), self._alarm_counter)

    def restore_state(self, state: tuple[dict[AlarmKey, Alarm], list[Alarm], int]) -> None:
        """Restore internal state from a snapshot."""
        active, cleared, counter = state
        self._active_alarms = dict(active)
        self._cleared_history = list(cleared)
        self._alarm_counter = counter

    def get_active_alarms(self) -> list[Alarm]:
        """Return a snapshot list of all currently active alarms."""
        return list(self._active_alarms.values())

    def get_cleared_alarms(self) -> list[Alarm]:
        """Return all historical cleared alarms."""
        return list(self._cleared_history)

    def get_all_alarms(self) -> list[Alarm]:
        """Return both active and cleared alarms."""
        return list(self._active_alarms.values()) + list(self._cleared_history)

    def get_active_alarm_by_key(self, key: AlarmKey) -> Optional[Alarm]:
        """Look up an active alarm by its deduplication key."""
        return self._active_alarms.get(key)
