"""Evaluation models and reporting structures for detection benchmarking."""

from dataclasses import dataclass
from datetime import datetime
from typing import Optional


@dataclass(frozen=True)
class FaultDetectionMatch:
    """Record of a ground-truth fault evaluated against raised alarms.

    Attributes:
        fault_id: Identifier of the injected fault.
        fault_type: Category of the fault.
        target_id: Target entity identifier.
        start_time: UTC fault activation timestamp.
        end_time: UTC fault recovery timestamp.
        affected_node_ids: Ground-truth impacted nodes.
        detected: Whether at least one eligible alarm was raised for this fault.
        matching_alarm_ids: Identifiers of alarms that matched this fault.
        detection_delay_seconds: Seconds from fault start_time to earliest matching alarm (or None).
    """

    fault_id: str
    fault_type: str
    target_id: str
    start_time: datetime
    end_time: datetime
    affected_node_ids: tuple[str, ...]
    detected: bool
    matching_alarm_ids: tuple[str, ...]
    detection_delay_seconds: Optional[float] = None


@dataclass(frozen=True)
class EvaluationReport:
    """Benchmark evaluation summary comparing detection outputs to ground truth.

    Attributes:
        total_faults: Number of injected ground-truth fault events.
        detected_faults: True positive fault events (detected >= 1 matching alarm).
        undetected_faults: False negative fault events (zero matching alarms).
        total_alarms: Total unique alarms generated by the detection engine.
        true_positive_alarms: Unique alarms raised on affected nodes during valid fault windows.
        false_positive_alarms: Unique alarms raised outside any active fault window / blast radius.
        alarm_precision: Proportion of unique alarms that corresponded to real faults (TP_alarms / total_alarms).
        fault_recall: Proportion of injected faults that were successfully detected (detected_faults / total_faults).
        hybrid_f1_score: Harmonic mean of alarm_precision and fault_recall, balancing alarm precision and fault recall.
        mean_time_to_detect_seconds: Average latency from fault start_time to earliest matching alarm across detected faults.
        fault_matches: Detailed match records per ground-truth fault.
        unmatched_alarm_ids: Identifiers of alarms that did not match any injected fault.
        precision: Backwards-compatible alias for alarm_precision.
        recall: Backwards-compatible alias for fault_recall.
        f1_score: Backwards-compatible alias for hybrid_f1_score.
    """

    total_faults: int
    detected_faults: int
    undetected_faults: int
    total_alarms: int
    true_positive_alarms: int
    false_positive_alarms: int
    alarm_precision: float = 0.0
    fault_recall: float = 0.0
    hybrid_f1_score: float = 0.0
    mean_time_to_detect_seconds: Optional[float] = None
    fault_matches: tuple[FaultDetectionMatch, ...] = ()
    unmatched_alarm_ids: tuple[str, ...] = ()
    precision: Optional[float] = None
    recall: Optional[float] = None
    f1_score: Optional[float] = None

    def __post_init__(self) -> None:
        if self.precision is not None and self.alarm_precision == 0.0:
            object.__setattr__(self, "alarm_precision", self.precision)
        if self.recall is not None and self.fault_recall == 0.0:
            object.__setattr__(self, "fault_recall", self.recall)
        if self.f1_score is not None and self.hybrid_f1_score == 0.0:
            object.__setattr__(self, "hybrid_f1_score", self.f1_score)

        if self.precision is None:
            object.__setattr__(self, "precision", self.alarm_precision)
        if self.recall is None:
            object.__setattr__(self, "recall", self.fault_recall)
        if self.f1_score is None:
            object.__setattr__(self, "f1_score", self.hybrid_f1_score)


@dataclass(frozen=True)
class RCAGroundTruthMatch:
    """Evaluation record comparing an injected fault to its diagnosed RCA hypothesis.

    Attributes:
        fault_id: Ground-truth fault identifier.
        fault_type: Expected fault category.
        target_id: Expected target entity identifier (node or link).
        matched_group_id: Matched correlation group ID, if any.
        diagnosed_cause_type: Cause category predicted by primary RCA hypothesis.
        diagnosed_target_id: Target entity predicted by primary RCA hypothesis.
        confidence_score: Confidence score of the primary hypothesis.
        cause_correct: Whether the diagnosed cause type matches ground truth.
        target_correct: Whether the diagnosed target matches ground truth (None if not independently verifiable).
        both_correct: Whether both cause type and target match ground truth.
        is_unknown: Whether the diagnosis concluded UNKNOWN / insufficient evidence.
        target_verifiable: Whether target correctness could be independently verified.
    """

    fault_id: str
    fault_type: str
    target_id: str
    matched_group_id: Optional[str]
    diagnosed_cause_type: Optional[str]
    diagnosed_target_id: Optional[str]
    confidence_score: Optional[float]
    cause_correct: bool
    target_correct: Optional[bool]
    both_correct: bool
    is_unknown: bool
    target_verifiable: bool = True


@dataclass(frozen=True)
class RCAEvaluationReport:
    """Benchmark evaluation summary comparing correlation and RCA results against ground truth.

    Attributes:
        total_faults: Number of injected ground-truth fault events.
        diagnosed_faults: Faults receiving a non-UNKNOWN diagnosis.
        correct_cause_count: Faults where top-1 cause type matched ground truth.
        correct_target_count: Faults where suspected target matched ground truth.
        correct_both_count: Faults where both cause type and target matched ground truth.
        unknown_count: Faults where RCA concluded UNKNOWN / INSUFFICIENT_EVIDENCE.
        misdiagnosed_count: Faults diagnosed with a non-UNKNOWN but incorrect cause type.
        unevaluable_target_count: Faults where target correctness could not be independently verified.
        top_1_cause_accuracy: Ratio of correct_cause_count / total_faults.
        target_accuracy: Ratio of correct_target_count / total_faults.
        both_accuracy: Ratio of correct_both_count / total_faults.
        diagnosis_coverage: Proportion of faults given a non-UNKNOWN diagnosis.
        total_alarms: Total unique alarms evaluated.
        total_groups: Total correlation groups formed.
        alarm_reduction_ratio: Noise reduction ratio (total_alarms - total_groups) / total_alarms.
        fault_matches: Detailed match records per ground-truth fault.
        unmatched_group_ids: Correlation group IDs that did not map to any injected fault.
    """

    total_faults: int
    diagnosed_faults: int
    correct_cause_count: int
    correct_target_count: int
    correct_both_count: int
    unknown_count: int
    misdiagnosed_count: int
    top_1_cause_accuracy: float
    target_accuracy: float
    both_accuracy: float
    diagnosis_coverage: float
    total_alarms: int
    total_groups: int
    alarm_reduction_ratio: float
    fault_matches: tuple[RCAGroundTruthMatch, ...] = ()
    unmatched_group_ids: tuple[str, ...] = ()
    unevaluable_target_count: int = 0
