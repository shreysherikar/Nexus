"""Evaluation models and reporting structures for detection benchmarking."""

from dataclasses import dataclass
from datetime import datetime
from typing import Optional


@dataclass(frozen=True)
class FaultDetectionMatch:
    """Record of a ground-truth fault evaluated against raised alarms.

    Attributes:
        fault_id: Identifier of the injected fault.
        fault_type: Category of the fault.
        target_id: Target entity identifier.
        start_time: UTC fault activation timestamp.
        end_time: UTC fault recovery timestamp.
        affected_node_ids: Ground-truth impacted nodes.
        detected: Whether at least one eligible alarm was raised for this fault.
        matching_alarm_ids: Identifiers of alarms that matched this fault.
        detection_delay_seconds: Seconds from fault start_time to earliest matching alarm (or None).
    """

    fault_id: str
    fault_type: str
    target_id: str
    start_time: datetime
    end_time: datetime
    affected_node_ids: tuple[str, ...]
    detected: bool
    matching_alarm_ids: tuple[str, ...]
    detection_delay_seconds: Optional[float] = None


@dataclass(frozen=True)
class EvaluationReport:
    """Benchmark evaluation summary comparing detection outputs to ground truth.

    Attributes:
        total_faults: Number of injected ground-truth fault events.
        detected_faults: True positive fault events (detected >= 1 matching alarm).
        undetected_faults: False negative fault events (zero matching alarms).
        total_alarms: Total unique alarms generated by the detection engine.
        true_positive_alarms: Unique alarms raised on affected nodes during valid fault windows.
        false_positive_alarms: Unique alarms raised outside any active fault window / blast radius.
        alarm_precision: Proportion of unique alarms that corresponded to real faults (TP_alarms / total_alarms).
        fault_recall: Proportion of injected faults that were successfully detected (detected_faults / total_faults).
        hybrid_f1_score: Harmonic mean of alarm_precision and fault_recall, balancing alarm precision and fault recall.
        mean_time_to_detect_seconds: Average latency from fault start_time to earliest matching alarm across detected faults.
        fault_matches: Detailed match records per ground-truth fault.
        unmatched_alarm_ids: Identifiers of alarms that did not match any injected fault.
        precision: Backwards-compatible alias for alarm_precision.
        recall: Backwards-compatible alias for fault_recall.
        f1_score: Backwards-compatible alias for hybrid_f1_score.
    """

    total_faults: int
    detected_faults: int
    undetected_faults: int
    total_alarms: int
    true_positive_alarms: int
    false_positive_alarms: int
    alarm_precision: float = 0.0
    fault_recall: float = 0.0
    hybrid_f1_score: float = 0.0
    mean_time_to_detect_seconds: Optional[float] = None
    fault_matches: tuple[FaultDetectionMatch, ...] = ()
    unmatched_alarm_ids: tuple[str, ...] = ()
    precision: Optional[float] = None
    recall: Optional[float] = None
    f1_score: Optional[float] = None

    def __post_init__(self) -> None:
        if self.precision is not None and self.alarm_precision == 0.0:
            object.__setattr__(self, "alarm_precision", self.precision)
        if self.recall is not None and self.fault_recall == 0.0:
            object.__setattr__(self, "fault_recall", self.recall)
        if self.f1_score is not None and self.hybrid_f1_score == 0.0:
            object.__setattr__(self, "hybrid_f1_score", self.f1_score)

        if self.precision is None:
            object.__setattr__(self, "precision", self.alarm_precision)
        if self.recall is None:
            object.__setattr__(self, "recall", self.fault_recall)
        if self.f1_score is None:
            object.__setattr__(self, "f1_score", self.hybrid_f1_score)
