"""Domain models and data structures for Root Cause Analysis (RCA)."""

from dataclasses import dataclass, field
from datetime import datetime
from enum import Enum
import math
from typing import Any, Mapping, Optional, Sequence

from nexus.detection.models import Severity, _freeze_evidence, _normalize_utc_timestamp
from nexus.rca.exceptions import InvalidRCAConfigError


class RootCauseType(str, Enum):
    """Categorization of diagnosed root-cause network conditions."""

    BACKHAUL_FAILURE = "BACKHAUL_FAILURE"
    SITE_POWER_FAILURE = "SITE_POWER_FAILURE"
    RADIO_INTERFERENCE = "RADIO_INTERFERENCE"
    CELL_CONGESTION = "CELL_CONGESTION"
    CELL_OUTAGE = "CELL_OUTAGE"
    UNKNOWN = "UNKNOWN"

    def __str__(self) -> str:
        return self.value


class TargetType(str, Enum):
    """Type of entity identified as the root-cause target."""

    NODE = "NODE"
    TRANSPORT_LINK = "TRANSPORT_LINK"
    UNKNOWN = "UNKNOWN"

    def __str__(self) -> str:
        return self.value


@dataclass(frozen=True)
class EvidenceItem:
    """A granular piece of diagnostic evidence supporting an RCA hypothesis.

    Attributes:
        source_node_id: Identifier of the network entity exhibiting the symptom.
        metric_name: Name of the observed telemetry metric or condition.
        observed_value: Observed metric value.
        threshold_or_baseline: Reference threshold or baseline against which violation occurred.
        reasoning: Human-readable diagnostic reasoning connecting the symptom to the hypothesis.
        severity: Alarm severity associated with this evidence, if applicable.
        evidence_source: Source of this evidence item ('ALARM', 'SNAPSHOT', or 'TOPOLOGY').
    """

    source_node_id: str
    metric_name: str
    observed_value: float
    threshold_or_baseline: Optional[float]
    reasoning: str
    severity: Optional[Severity] = None
    evidence_source: str = "ALARM"

    def __post_init__(self) -> None:
        if not isinstance(self.source_node_id, str) or not self.source_node_id.strip():
            raise ValueError("source_node_id must be a non-empty string")
        if not isinstance(self.metric_name, str) or not self.metric_name.strip():
            raise ValueError("metric_name must be a non-empty string")
        if not isinstance(self.reasoning, str):
            raise ValueError("reasoning must be a string")
        if self.evidence_source not in ("ALARM", "SNAPSHOT", "TOPOLOGY"):
            raise ValueError(f"Invalid evidence_source: '{self.evidence_source}', must be 'ALARM', 'SNAPSHOT', or 'TOPOLOGY'")


@dataclass(frozen=True)
class RootCauseHypothesis:
    """An explainable, ranked root-cause hypothesis generated by diagnostic rules.

    Attributes:
        hypothesis_id: Unique deterministic identifier for this hypothesis.
        cause_type: Diagnosed root cause category.
        target_id: Identifier of the suspected target node or transport link.
        target_type: Whether the target is a NODE or a TRANSPORT_LINK.
        confidence_score: Heuristic evidence-support score strictly bounded in [0.0, 1.0].
        explanation: Human-readable diagnostic summary.
        evidence_items: Granular evidence items supporting this conclusion.
        group_id: Correlation group from which this hypothesis was derived.
    """

    hypothesis_id: str
    cause_type: RootCauseType
    target_id: str
    target_type: TargetType
    confidence_score: float
    explanation: str
    evidence_items: tuple[EvidenceItem, ...]
    group_id: str

    def __post_init__(self) -> None:
        if not isinstance(self.hypothesis_id, str) or not self.hypothesis_id.strip():
            raise ValueError("hypothesis_id must be a non-empty string")
        if not isinstance(self.target_id, str) or not self.target_id.strip():
            raise ValueError("target_id must be a non-empty string")
        if not isinstance(self.group_id, str) or not self.group_id.strip():
            raise ValueError("group_id must be a non-empty string")

        if not isinstance(self.cause_type, RootCauseType):
            try:
                object.__setattr__(self, "cause_type", RootCauseType(self.cause_type))
            except ValueError as exc:
                raise ValueError(f"Invalid RootCauseType: {self.cause_type}") from exc

        if not isinstance(self.target_type, TargetType):
            try:
                object.__setattr__(self, "target_type", TargetType(self.target_type))
            except ValueError as exc:
                raise ValueError(f"Invalid TargetType: {self.target_type}") from exc

        # Score validation: must be finite float in [0.0, 1.0]
        if isinstance(self.confidence_score, bool) or not isinstance(self.confidence_score, (int, float)):
            raise ValueError(f"confidence_score must be a float, got {type(self.confidence_score).__name__}")
        f_score = float(self.confidence_score)
        if not math.isfinite(f_score) or f_score < 0.0 or f_score > 1.0:
            raise ValueError(f"confidence_score must be a finite float between 0.0 and 1.0, got {f_score}")
        object.__setattr__(self, "confidence_score", round(f_score, 4))

        if not isinstance(self.evidence_items, tuple):
            object.__setattr__(self, "evidence_items", tuple(self.evidence_items))


@dataclass(frozen=True)
class RCAResult:
    """Complete root-cause analysis result for a correlation group.

    Attributes:
        group_id: Correlation group evaluated.
        hypotheses: Ranked tuple of RootCauseHypothesis instances, ordered by confidence descending.
        primary_hypothesis: Top-ranked hypothesis if confidence exceeds threshold, else None.
        analysis_timestamp: UTC timestamp of when analysis was conducted.
        recommended_action: Suggested operational remediation or next troubleshooting step.
    """

    group_id: str
    hypotheses: tuple[RootCauseHypothesis, ...]
    primary_hypothesis: Optional[RootCauseHypothesis]
    analysis_timestamp: datetime
    recommended_action: Optional[str] = None

    def __post_init__(self) -> None:
        if not isinstance(self.group_id, str) or not self.group_id.strip():
            raise ValueError("group_id must be a non-empty string")

        ts = _normalize_utc_timestamp("analysis_timestamp", self.analysis_timestamp)
        object.__setattr__(self, "analysis_timestamp", ts)

        if not isinstance(self.hypotheses, tuple):
            object.__setattr__(self, "hypotheses", tuple(self.hypotheses))


@dataclass(frozen=True)
class RCAConfig:
    """Configuration for the RootCauseAnalysisEngine.

    Attributes:
        min_confidence_threshold: Minimum score required for a hypothesis to be selected as primary (default 0.35).
        max_hypotheses_per_group: Maximum number of hypotheses returned per group (default 5).
        max_telemetry_staleness_seconds: Maximum allowed time delta between group window and valid telemetry snapshot (default 300.0s).
    """

    min_confidence_threshold: float = 0.35
    max_hypotheses_per_group: int = 5
    max_telemetry_staleness_seconds: float = 300.0

    def __post_init__(self) -> None:
        if isinstance(self.min_confidence_threshold, bool) or not isinstance(self.min_confidence_threshold, (int, float)):
            raise InvalidRCAConfigError("min_confidence_threshold must be a float")
        f_thresh = float(self.min_confidence_threshold)
        if not math.isfinite(f_thresh) or f_thresh < 0.0 or f_thresh > 1.0:
            raise InvalidRCAConfigError(f"min_confidence_threshold must be between 0.0 and 1.0, got {f_thresh}")
        object.__setattr__(self, "min_confidence_threshold", f_thresh)

        if isinstance(self.max_hypotheses_per_group, bool) or not isinstance(self.max_hypotheses_per_group, int) or self.max_hypotheses_per_group < 1:
            raise InvalidRCAConfigError("max_hypotheses_per_group must be an integer >= 1")

        if isinstance(self.max_telemetry_staleness_seconds, bool) or not isinstance(self.max_telemetry_staleness_seconds, (int, float)):
            raise InvalidRCAConfigError("max_telemetry_staleness_seconds must be a float")
        f_stale = float(self.max_telemetry_staleness_seconds)
        if not math.isfinite(f_stale) or f_stale <= 0.0:
            raise InvalidRCAConfigError(f"max_telemetry_staleness_seconds must be a positive finite float, got {f_stale}")
        object.__setattr__(self, "max_telemetry_staleness_seconds", f_stale)
